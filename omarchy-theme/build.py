#!/usr/bin/env python3
"""Build the Skogai Arcade Omarchy theme from the design system's tokens.json.

    ./build.py             # build into ./theme/
    ./build.py --install   # also install fonts, copy to ~/.config/omarchy/themes/skogai-arcade, apply it

Source of truth: the Skogai Arcade Design System artifact
(https://claude.ai/artifact/371MkW11ooVU5uxkdVWCob). Refresh tokens.json, scenes/ and
fonts/ from it before building when the design system changes.
"""
import json, os, shutil, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
THEME_DIR = os.path.join(HERE, "theme")
INSTALL_DIR = os.path.expanduser("~/.config/omarchy/themes/skogai-arcade")
FONT_DIR = os.path.expanduser("~/.local/share/fonts/skogai")
SYSTEM_FONT = "BigBlueTermPlus Nerd Font Mono"

# Omarchy colors.toml key -> design-system token (or a literal "#hex" where the system has none)
MAPPING = {
    "accent": "sk-primary",
    "selection": "sk-card-2",
    "muted": "sk-fg-dim",
    "background": "sk-bg",
    "dark_background": "#08050f",
    "darker_background": "#05030a",
    "lighter_background": "sk-shell",
    "foreground": "sk-fg",
    "dark_foreground": "sk-fg-muted",
    "light_foreground": "sk-fg-2",
    "bright_foreground": "sk-fg",
    "red": "sk-neon-red",
    "yellow": "sk-neon-yellow",
    "orange": "sk-neon-orange",
    "green": "sk-neon-green",
    "cyan": "sk-neon-cyan",
    "blue": "sk-neon-blue",
    "magenta": "sk-neon-violet",
    "brown": "#8a5a3c",
    "bright_red": "sk-neon-red",
    "bright_yellow": "sk-neon-yellow",
    "bright_green": "sk-neon-acid",
    "bright_cyan": "sk-neon-teal",
    "bright_blue": "sk-neon-blue",
    "bright_magenta": "sk-neon-pink",
}
BORDER_ACTIVE = ("sk-primary", "sk-accent")
BORDER_INACTIVE = "sk-border"

# wallpaper order: generated pixel art + framed scenes (scenes/<stem>.*)
BACKGROUNDS = [
    ("1-grid-horizon", "gen:grid"),
    ("2-sudo-hero", "scene:scene-sudo-hero"),
    ("3-wifi-wizards", "scene:scene-wifi-wizards"),
    ("4-honkers-hackers", "scene:scene-honkers-hackers"),
    ("5-skognet-syndicate", "scene:scene-skognet-syndicate"),
    ("6-neon-city", "gen:city"),
    ("7-neon-rain", "gen:rain"),
]


def load_tokens():
    data = json.load(open(os.path.join(HERE, "tokens.json")))
    tok = {t["name"]: t["value"] for t in data["color"]["tokens"]}

    def resolve(name):
        if name.startswith("#"):
            return name
        v = tok[name]
        while isinstance(v, str) and v.startswith("{"):
            v = tok[v[1:-1]]
        if isinstance(v, dict):  # themed value: take the first theme
            v = next(iter(v.values()))
        return v.lower()

    return resolve


def write_colors(resolve):
    a, b = (resolve(n).lstrip("#") for n in BORDER_ACTIVE)
    lines = [
        "# Skogai Arcade -- generated by build.py from the design system's tokens.json",
        'mode = "dark"',
        f'hyprland_active_border = "rgba({a}ee) rgba({b}ee) 45deg"',
        f'hyprland_inactive_border = "rgba({resolve(BORDER_INACTIVE).lstrip("#")}aa)"',
        "",
    ]
    for key, src in MAPPING.items():
        note = f"  # {src}" if not src.startswith("#") else ""
        lines.append(f'{key} = "{resolve(src)}"{note}')
    open(os.path.join(THEME_DIR, "colors.toml"), "w").write("\n".join(lines) + "\n")


def build_backgrounds(resolve):
    bg_dir = os.path.join(THEME_DIR, "backgrounds")
    os.makedirs(bg_dir, exist_ok=True)
    canvas, frame = resolve("sk-bg"), resolve("sk-card-2")
    with tempfile.TemporaryDirectory() as tmp:
        subprocess.run([sys.executable, "-I", os.path.join(HERE, "pixel_wallpapers.py"),
                        os.path.join(HERE, "tokens.json"), tmp], check=True)
        for name, spec in BACKGROUNDS:
            kind, stem = spec.split(":")
            out = os.path.join(bg_dir, name + ".png")
            if kind == "gen":
                subprocess.run(["magick", os.path.join(tmp, stem + ".ppm"),
                                "-filter", "point", "-resize", "400%", out], check=True)
            else:
                src = next(os.path.join(HERE, "scenes", f) for f in os.listdir(os.path.join(HERE, "scenes"))
                           if os.path.splitext(f)[0] == stem)
                subprocess.run(["magick",
                    "(", src, "-resize", "2560x1440^", "-gravity", "center", "-extent", "2560x1440",
                         "-scale", "4%", "-scale", "2500%", "-fill", canvas, "-colorize", "55%", ")",
                    "(", src, "-filter", "point", "-resize", "x1440", "-bordercolor", frame, "-border", "4x0", ")",
                    "-gravity", "center", "-composite", "-resize", "2560x1440!", out], check=True)


def install():
    os.makedirs(FONT_DIR, exist_ok=True)
    for f in os.listdir(os.path.join(HERE, "fonts")):
        shutil.copy2(os.path.join(HERE, "fonts", f), FONT_DIR)
    subprocess.run(["fc-cache", "-f", FONT_DIR], check=True)
    shutil.rmtree(INSTALL_DIR, ignore_errors=True)
    shutil.copytree(THEME_DIR, INSTALL_DIR)
    subprocess.run(["omarchy", "theme", "set", "skogai-arcade"], check=True)
    subprocess.run(["omarchy", "font", "set", SYSTEM_FONT], check=True)


def main():
    os.makedirs(THEME_DIR, exist_ok=True)
    resolve = load_tokens()
    write_colors(resolve)
    with open(os.path.join(THEME_DIR, "icons.theme"), "w") as f:
        f.write("Yaru-purple-dark\n")
    build_backgrounds(resolve)
    print(f"built {THEME_DIR}")
    if "--install" in sys.argv:
        install()
        print("installed and applied skogai-arcade")


if __name__ == "__main__":
    main()
